#!/usr/bin/env bash
# Install the platform on the kind cluster: Agent Substrate and kagent (through the
# pinned kagent CLI, the install path kagent 1.x documents), agentgateway with the
# OpenCode Go key Secret, Argo CD, and the teams of platform/teams.txt (charts/teams), whose
# agents Argo CD deploys from deployments/. Usage: [GITOPS_REVISION=<branch>] install.sh
# Every chart's registry digest is checked against platform/versions.env first.
# The key goes from .env to kubectl on stdin; it is never printed, written to a file,
# or put on a command line.
set -euo pipefail
# shellcheck source=platform/lib.sh
. "$(dirname "$0")/lib.sh"

READY_TIMEOUT="${READY_TIMEOUT:-600s}"
CHART_DIR="$BIN_DIR/charts"
KUBECONFIG_FILE="$BIN_DIR/$CTX.kubeconfig"
CLI_CONFIG="$BIN_DIR/kagent-cli.yaml"
PINS_VALUES="$BIN_DIR/kagent-pins.yaml"
# platform/substrate-values.yaml plus a namespace policy per team (platform/teams.sh).
SUBSTRATE_VALUES="$BIN_DIR/substrate-values.yaml"
# The namespace every agent lived in before the teams; make up deletes it.
LEGACY_AGENTS_NS="agents"
# kagent's chart makes Secret kagent-openai from this; the gateway ignores it.
PLACEHOLDER_KEY="not-used-agentgateway-holds-the-key"

# pull_verified REPO CHART VERSION DIGEST: pull the chart into CHART_DIR and fail
# unless the registry's digest for that version is the pinned one.
pull_verified() {
  local repo="$1" chart="$2" version="$3" want="$4" out got
  mkdir -p "$CHART_DIR"
  out="$(helm pull "$repo/$chart" --version "$version" -d "$CHART_DIR" 2>&1)" ||
    fail "could not pull chart $chart $version: $(first_line "$out")"
  got="$(printf '%s\n' "$out" | awk '/^Digest:/ {print $2}')"
  [ "$got" = "$want" ] ||
    fail "chart $chart $version has digest ${got:-none}, pinned $want (platform/versions.env)"
  echo "chart $chart $version digest ok"
}

verify_charts() {
  pull_verified "$KAGENT_CHART_REPO" kagent-crds "$KAGENT_VERSION" "$KAGENT_CRDS_CHART_DIGEST"
  pull_verified "$KAGENT_CHART_REPO" kagent "$KAGENT_VERSION" "$KAGENT_CHART_DIGEST"
  pull_verified "$SUBSTRATE_CHART_REPO" substrate-crds "$SUBSTRATE_VERSION" "$SUBSTRATE_CRDS_CHART_DIGEST"
  pull_verified "$SUBSTRATE_CHART_REPO" substrate "$SUBSTRATE_VERSION" "$SUBSTRATE_CHART_DIGEST"
  pull_verified "$SUBSTRATE_CHART_REPO" substrate-podcert "$SUBSTRATE_VERSION" "$SUBSTRATE_PODCERT_CHART_DIGEST"
  pull_verified "$AGW_CHART_REPO" agentgateway-crds "$AGW_VERSION" "$AGW_CRDS_CHART_DIGEST"
  pull_verified "$AGW_CHART_REPO" agentgateway "$AGW_VERSION" "$AGW_CHART_DIGEST"
  pull_verified "$ARGOCD_CHART_REPO" argo-cd "$ARGOCD_CHART_VERSION" "$ARGOCD_CHART_DIGEST"
}

# download_verified URL SHA256 DEST: fetch to DEST, failing on a checksum mismatch.
download_verified() {
  local url="$1" want="$2" dest="$3" tmp got
  tmp="$(mktemp "$dest.XXXXXX")"
  curl -fsSL -o "$tmp" "$url" || { rm -f "$tmp"; fail "could not download $url"; }
  got="$(shasum -a 256 "$tmp" | awk '{print $1}')"
  if [ "$got" != "$want" ]; then
    rm -f "$tmp"
    fail "checksum mismatch for $url (pinned $want, got $got)"
  fi
  mv "$tmp" "$dest"
}

# The CLI is kept as downloaded (kagent.unsigned) next to the signed copy, so a rerun
# can check the pinned checksum without downloading again.
fetch_kagent_cli() {
  local target var have=""
  target="$(os_arch)"
  var="KAGENT_CLI_SHA256_$(printf '%s' "$target" | tr '[:lower:]-' '[:upper:]_')"
  [ -n "${!var:-}" ] || fail "no pinned kagent CLI checksum for $target"
  if [ -x "$BIN_DIR/kagent" ] && [ -f "$BIN_DIR/kagent.unsigned" ]; then
    have="$(shasum -a 256 "$BIN_DIR/kagent.unsigned" | awk '{print $1}')"
  fi
  if [ "$have" = "${!var}" ]; then return 0; fi
  mkdir -p "$BIN_DIR"
  download_verified "$KAGENT_CLI_URL/kagent-$target" "${!var}" "$BIN_DIR/kagent.unsigned"
  cp "$BIN_DIR/kagent.unsigned" "$BIN_DIR/kagent"
  chmod +x "$BIN_DIR/kagent"
  # macOS kills a downloaded binary until it carries an ad-hoc signature.
  if [ "$(uname -s)" = Darwin ]; then
    codesign --force -s - "$BIN_DIR/kagent" || fail "could not ad-hoc sign $BIN_DIR/kagent"
  fi
}

# The kagent CLI calls helm and kubectl without a context flag, so it gets a
# kubeconfig that holds only this cluster's context.
write_cli_files() {
  (umask 077 && kind get kubeconfig --name "$CLUSTER" >"$KUBECONFIG_FILE")
  "$TEAMS_SH" substrate-values >"$SUBSTRATE_VALUES"
  cat >"$CLI_CONFIG" <<EOF
# Generated by platform/install.sh from platform/versions.env.
install:
  defaultModelProvider: OpenAI
  kagent:
    repository: $KAGENT_CHART_REPO/
    version: $KAGENT_VERSION
    valuesFiles: [$PLATFORM_DIR/kagent-values.yaml, $PINS_VALUES]
  substrate:
    repository: $SUBSTRATE_CHART_REPO/
    version: $SUBSTRATE_VERSION
    valuesFiles: [$SUBSTRATE_VALUES]
  podCertificate:
    repository: $SUBSTRATE_CHART_REPO/
    version: $SUBSTRATE_VERSION
  bundledPostgresImage: $POSTGRES_IMAGE
EOF
  cat >"$PINS_VALUES" <<EOF
# Generated by platform/install.sh from platform/versions.env.
controller:
  image:
    digest: $KAGENT_CONTROLLER_DIGEST
ui:
  image:
    digest: $KAGENT_UI_DIGEST
substrateWorkerPool:
  workerImage: $SUBSTRATE_WORKER_IMAGE
EOF
}

install_substrate_and_kagent() {
  local releases release missing=0
  releases="$(h list -A --deployed -q)" || fail "could not list Helm releases"
  for release in kagent-crds substrate-crds substrate-podcert substrate kagent; do
    # shellcheck disable=SC2310  # predicate: is the release deployed
    has_line "$release" "$releases" || missing=1
  done
  if [ "$missing" = 0 ]; then
    echo "Substrate and kagent releases are deployed; not reinstalling them"
    return 0
  fi
  KUBECONFIG="$KUBECONFIG_FILE" OPENAI_API_KEY="$PLACEHOLDER_KEY" \
    "$BIN_DIR/kagent" --config "$CLI_CONFIG" install --namespace "$KAGENT_NS"
}

install_gateway() {
  download_verified "$GATEWAY_CRDS_URL" "$GATEWAY_CRDS_FILE_SHA256" "$BIN_DIR/gateway-crds.yaml"
  k apply --server-side -f "$BIN_DIR/gateway-crds.yaml" >/dev/null
  h upgrade --install agentgateway-crds "$CHART_DIR/agentgateway-crds-$AGW_VERSION.tgz" \
    -n "$AGW_NS" --create-namespace --wait
  h upgrade --install agentgateway "$CHART_DIR/agentgateway-$AGW_VERSION.tgz" \
    -n "$AGW_NS" --wait --timeout "$READY_TIMEOUT"
}

# Delete and create, not apply: apply would copy the key into the Secret's
# last-applied-configuration annotation. printf is a builtin, so the key reaches
# kubectl on stdin and is in no process's argv.
make_key_secret() {
  local key
  key="$(read_key)"
  [ -n "$key" ] || fail "$KEY_NAME is missing or empty in $ENV_FILE"
  k delete secret "$KEY_SECRET" -n "$AGW_NS" --ignore-not-found >/dev/null
  printf %s "$key" | k create secret generic "$KEY_SECRET" -n "$AGW_NS" \
    --from-file=Authorization=/dev/stdin >/dev/null
  echo "Secret $AGW_NS/$KEY_SECRET made from $KEY_NAME"
}

apply_gateway() {
  k apply -f "$PLATFORM_DIR/gateway.yaml"
  k wait --for=condition=Programmed gateway/agentgateway-proxy -n "$AGW_NS" --timeout="$READY_TIMEOUT"
}

# Before the teams, every agent of ours shared one namespace (LEGACY_AGENTS_NS), from hand-written YAML.
# They are values files in team-platform now; a cluster built before the move loses the old one.
remove_legacy_agents_namespace() {
  k delete namespace "$LEGACY_AGENTS_NS" --ignore-not-found --timeout="$READY_TIMEOUT"
}

install_argocd() {
  h upgrade --install argocd "$CHART_DIR/argo-cd-$ARGOCD_CHART_VERSION.tgz" \
    -n "$ARGOCD_NS" --create-namespace -f "$PLATFORM_DIR/argocd-values.yaml" \
    --set "global.image.tag=$ARGOCD_IMAGE_TAG" --set "redis.image.tag=$ARGOCD_REDIS_IMAGE_TAG" \
    --wait --timeout "$READY_TIMEOUT"
}

# Each team on the list gets team-<team>, its team base, and its AppProject; the one
# ApplicationSet then deploys every deployments/<team>/<agent>/ folder at GITOPS_REVISION.
# The minter (agent/src/minter/, a CronJob in the teams release) runs its TypeScript source
# on the pinned node image: each file goes in as minter.source.<name without .ts>.
install_teams() {
  local names teams_json file minter_args=()
  names="$("$TEAMS_SH" names)"
  teams_json="$(printf '%s\n' "$names" | jq -R . | jq -cs .)"
  for file in "$ROOT"/agent/src/minter/*.ts; do
    minter_args+=(--set-file "minter.source.$(basename "$file" .ts)=$file")
  done
  # --reset-then-reuse-values keeps the image pins make deploy set (images.*) on a rerun.
  h upgrade --install teams "$PLATFORM_DIR/charts/teams" -n "$ARGOCD_NS" --reset-then-reuse-values \
    --set-json "teams=$teams_json" --set "workerImage=$SUBSTRATE_WORKER_IMAGE" \
    --set "minter.image=$NODE_IMAGE" "${minter_args[@]}" \
    --set "argocdNamespace=$ARGOCD_NS" \
    --set "gitops.repoURL=$GITOPS_REPO_URL" --set "gitops.revision=$GITOPS_REVISION" \
    --wait --timeout "$READY_TIMEOUT"
  echo "teams installed: $(printf '%s' "$names" | tr '\n' ' '); Argo CD tracks $GITOPS_REPO_URL at $GITOPS_REVISION"
}

# `make up` runs preflight.sh before it creates anything; run it here only when this
# script is called on its own.
if [ -z "${PREFLIGHT_DONE:-}" ]; then "$PLATFORM_DIR/preflight.sh"; fi
verify_charts
fetch_kagent_cli
write_cli_files
install_substrate_and_kagent
install_gateway
make_key_secret
apply_gateway
remove_legacy_agents_namespace
install_argocd
install_teams
echo "platform is up on $CTX; total time ${SECONDS}s"
